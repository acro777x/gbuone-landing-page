/**
 * Generates the website's PUBLIC Supabase config from environment variables
 * or a local .env file.
 *
 *   Local:     node setup_landing_config.js ../gbu-one/.env
 *   Cloudflare Pages / Workers build:  node setup_landing_config.js
 *              with EXPO_PUBLIC_SUPABASE_URL and EXPO_PUBLIC_SUPABASE_ANON_KEY
 *              set in the dashboard's Environment variables.
 *
 * HARD SECURITY RULES (fail closed):
 *   - the key MUST be sb_publishable_...;
 *   - sb_secret_, service-role and legacy JWT keys are REJECTED;
 *   - only two allowlisted values reach auth/config.js. Nothing else from
 *     the environment or .env is copied.
 */
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const ENV_FILE = process.argv[2] ? path.resolve(process.argv[2]) : path.join(ROOT, '.env');
const OUT = path.join(ROOT, 'auth', 'config.js');

function readEnvFile(file) {
  const values = {};
  if (!fs.existsSync(file)) return values;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/.exec(line);
    if (match) values[match[1]] = match[2].replace(/^["']|["']$/g, '');
  }
  return values;
}

function fail(message) {
  console.error('REFUSING TO WRITE WEBSITE CONFIG: ' + message);
  process.exit(1);
}

function main() {
  // Environment variables win on Cloudflare; .env is the local fallback.
  const fileValues = readEnvFile(ENV_FILE);
  const url = (process.env.EXPO_PUBLIC_SUPABASE_URL || fileValues.EXPO_PUBLIC_SUPABASE_URL || '').trim();
  const key = (process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY || fileValues.EXPO_PUBLIC_SUPABASE_ANON_KEY || '').trim();

  if (!/^https:\/\/[a-z0-9-]+\.supabase\.co\/?$/.test(url)) {
    fail('EXPO_PUBLIC_SUPABASE_URL is missing or is not a Supabase project URL. On Cloudflare, add it under Settings -> Environment variables.');
  }
  if (!/^sb_publishable_[A-Za-z0-9_-]+$/.test(key)) {
    fail('EXPO_PUBLIC_SUPABASE_ANON_KEY must be an sb_publishable_... key. Never publish a secret/service-role key.');
  }
  if (/sb_secret_|service_role|eyJ[A-Za-z0-9_-]{10,}/i.test(key)) {
    fail('the configured key looks privileged; refusing.');
  }

  const payload = [
    '/** AUTO-GENERATED by setup_landing_config.js - DO NOT EDIT. */',
    '/** PUBLIC values only. This file is served to every website visitor. */',
    'window.GBU_ONE_CONFIG = ' +
      JSON.stringify({ SUPABASE_URL: url, PUBLISHABLE_KEY: key }, null, 2) +
      ';',
    '',
  ].join('\n');

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, payload, 'utf8');
  console.log('Wrote auth/config.js');
  console.log('Key: ' + key.slice(0, 18) + '... (publishable, safe for a public site)');
}

main();
